const EN = new Map<string, string>();
const HE = new Map<string, string>();
for (const [pt, en, he] of ROWS) {
  EN.set(pt, en);
  HE.set(pt, he);
}
for (const p of PARASHOT) {
  EN.set(p.namePt, parashaName(p, 'en'));
  HE.set(p.namePt, p.nameHe);
}
for (const w of WORLDS) {
  if (!EN.has(w.namePt)) EN.set(w.namePt, w.namePt);
  HE.set(w.namePt, w.nameHe);
}

/** Texto do catálogo no idioma pedido (volta o português se não houver tradução). */
export function catalogText(pt: string, locale: Locale): string {
  if (locale === 'pt') return pt;
  return (locale === 'en' ? EN : HE).get(pt) ?? pt;
}

/** A frase tem tradução no catálogo para o idioma (o português sempre tem). */
export function hasCatalogText(pt: string, locale: Locale): boolean {
  return locale === 'pt' || (locale === 'en' ? EN : HE).has(pt);
}

/** Para os testes: frases do catálogo sem tradução. */
export function catalogMissing(pts: readonly string[], locale: Exclude<Locale, 'pt'>): string[] {
  const map = locale === 'en' ? EN : HE;
  return pts.filter((p) => !map.has(p));
}
